import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { stringify } from 'yaml';
import { LocalBlobStore } from '../packages/infrastructure/src/blobs.ts';
import { createRegistry } from '../packages/application/src/registry.ts';
import { buildOpenApi, type JsonSchema } from '../packages/contracts/src/openapi.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
const start = '// BEGIN GENERATED COMMAND PAYLOAD TYPES';
const end = '// END GENERATED COMMAND PAYLOAD TYPES';

// This intentionally small emitter covers JSON Schema produced by the current
// registry and fails on unsupported types rather than silently widening inputs.
export function schemaType(schema: JsonSchema | boolean): string {
  if (schema === true) return 'unknown';
  if (schema === false) return 'never';
  if (schema.$ref) throw new Error('Payload schema references require explicit emitter support');
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value: unknown) => JSON.stringify(value)).join(' | ');
  if (schema.anyOf || schema.oneOf) return (schema.anyOf ?? schema.oneOf).map((value: JsonSchema) => `(${schemaType(value)})`).join(' | ');
  if (schema.allOf) return schema.allOf.map((value: JsonSchema) => `(${schemaType(value)})`).join(' & ');
  if (Array.isArray(schema.type)) return schema.type.map((type: string) => `(${schemaType({ ...schema, type })})`).join(' | ');
  switch (schema.type) {
    case 'string': return 'string';
    case 'number': case 'integer': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `Array<${schemaType(schema.items ?? true)}>`;
    case 'object': {
      const entries = Object.entries(schema.properties ?? {}).map(([name, child]) => `${JSON.stringify(name)}${schema.required?.includes(name) ? '' : '?'}: ${schemaType(child as JsonSchema)};`);
      if (schema.additionalProperties !== false) entries.push(`[key: string]: ${schemaType(schema.additionalProperties ?? true)};`);
      return entries.length ? `{ ${entries.join(' ')} }` : 'Record<string, never>';
    }
    case undefined:
      if (Object.keys(schema).length === 0) return 'unknown';
      throw new Error(`Unrecognized payload schema: ${JSON.stringify(schema)}`);
    default: throw new Error(`Unsupported payload schema type: ${schema.type}`);
  }
}

export async function generateContracts(check = false, outputRoot = root): Promise<void> {
  // Constructing a store is inert: no database, credentials or content needed.
  const document = buildOpenApi(createRegistry(new LocalBlobStore(path.join(root, '.local', 'contract-generation-unused'))));
  const names = Object.keys(document.components.schemas.Command!.discriminator.mapping).sort();
  const generated = `${start}\nexport type CommandPayloadMap = {\n${names.map(name => `  ${name}: ${schemaType(document.components.schemas[`${name}Payload`]!)};`).join('\n')}\n};\n${end}`;
  const clientPath = path.join(outputRoot, 'packages/contracts/src/client.ts');
  const clientSource = await readFile(clientPath, 'utf8');
  if (clientSource.split(start).length !== 2 || clientSource.split(end).length !== 2) throw new Error('Client must contain exactly one generated payload block');
  const updatedClient = clientSource.slice(0, clientSource.indexOf(start)) + generated + clientSource.slice(clientSource.indexOf(end) + end.length);
  const yamlPath = path.join(outputRoot, 'docs/contracts/openapi.yaml');
  const yaml = '# Generated by scripts/generate-contracts.ts. Do not edit by hand.\n' + stringify(document, { lineWidth: 120, aliasDuplicateObjects: false });
  const outputs = [[clientPath, updatedClient], [yamlPath, yaml]] as const;
  const drift: string[] = [];
  for (const [file, expected] of outputs) {
    if (check) {
      const current = await readFile(file, 'utf8').catch((error: NodeJS.ErrnoException) => { if (error.code === 'ENOENT') return ''; throw error; });
      if (current !== expected) drift.push(path.relative(outputRoot, file));
    } else {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, expected);
    }
  }
  if (drift.length) throw new Error(`Generated contracts are stale: ${drift.join(', ')}. Run pnpm contracts:generate.`);
  console.log(`${check ? 'Checked' : 'Generated'} OpenAPI ${document.openapi}, ${names.length} command payload types and ${Object.keys(document.paths).length} paths.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check') || args.length > 1) throw new Error('Usage: node scripts/generate-contracts.ts [--check]');
  await generateContracts(args.includes('--check'));
}
