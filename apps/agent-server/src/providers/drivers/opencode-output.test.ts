import assert from "node:assert/strict";
import test from "node:test";
import type { NativeOutputEvent, NativeOutputItem } from "@agent-workspace/contracts/output";
import { OpenCodeOutput } from "./opencode-output.ts";

function collect() {
  const events: NativeOutputEvent[] = [];
  const output = new OpenCodeOutput((event) => events.push(event));
  const items = () => events.flatMap((event) => event.type === "item.upsert" ? [event.item] : []);
  const latest = (id: string): NativeOutputItem | undefined => items().filter((item) => item.id === id).at(-1);
  return { output, events, items, latest };
}

test("OpenCode v1 maps assistant parts, tools, command snapshots and task children", () => {
  const { output, events, items, latest } = collect();
  const send = (type: string, properties: Record<string, unknown>) => output.update("v1", { type, properties });
  send("message.updated", { info: { id: "user", role: "user" } });
  send("message.part.updated", { part: { id: "user-part", messageID: "user", type: "text", text: "secret prompt" } });
  send("message.updated", { info: { id: "assistant", role: "assistant" } });
  send("message.part.updated", { part: { id: "text", messageID: "assistant", type: "text", text: "Hello" } });
  send("message.part.delta", { partID: "text", messageID: "assistant", field: "text", delta: " world" });
  send("message.part.updated", { part: { id: "text", messageID: "assistant", type: "text", text: "Hello world", time: { end: 1 } } });
  send("message.part.updated", { part: { id: "reason", messageID: "assistant", type: "reasoning", text: "Thinking", time: { end: 1 } } });
  const part = (tool: string, callID: string, state: object) => ({ part: { id: `part-${callID}`, messageID: "assistant", type: "tool", tool, callID, state } });
  send("message.part.updated", part("bash", "call", { status: "running", input: { command: "echo hello" }, metadata: { output: "hel" } }));
  const firstCommandItem = events.findIndex((event) => event.type === "item.upsert" && event.item.id === "opencode:tool:call");
  const firstCommandChunk = events.findIndex((event) => event.type === "command.output" && event.itemId === "opencode:tool:call");
  assert.ok(firstCommandItem >= 0 && firstCommandChunk > firstCommandItem);
  const runningCount = items().filter((item) => item.id === "opencode:tool:call").length;
  assert.equal(latest("opencode:tool:call")?.output, undefined);
  send("message.part.updated", part("bash", "call", { status: "running", input: { command: "echo hello" }, metadata: { output: "hell" } }));
  assert.equal(items().filter((item) => item.id === "opencode:tool:call").length, runningCount);
  send("message.part.updated", part("bash", "call", { status: "completed", input: { command: "echo hello" }, output: "hello\n", metadata: { exit: 0 } }));
  send("message.part.updated", part("bash", "call", { status: "completed", input: { command: "echo hello" }, output: "hello\n", metadata: { exit: 0 } }));
  send("message.part.updated", part("edit", "edit", { status: "completed", input: { filePath: "a.ts", oldString: "a", newString: "b" }, metadata: { diff: "-a\n+b" }, output: "ok" }));
  send("message.part.updated", part("task", "task", { status: "running", input: { prompt: "inspect" }, metadata: { sessionId: "child" } }));
  send("message.updated", { info: { id: "child-message", role: "assistant", sessionID: "child" } });
  send("message.part.updated", { part: { id: "child-part", sessionID: "child", messageID: "child-message", type: "text", text: "child" } });
  send("todo.updated", { sessionID: "root", todos: [{ content: "do it", status: "in_progress" }, { content: "done", status: "completed" }] });
  output.finish();
  assert.equal(latest("opencode:part:text")?.text, "Hello world");
  assert.equal(latest("opencode:part:text")?.status, "completed");
  assert.equal(latest("opencode:part:reason")?.type, "reasoning");
  assert.ok(!items().some((item) => item.text === "secret prompt"));
  assert.deepEqual(events.filter((event) => event.type === "command.output").map((event) => event.type === "command.output" && event.chunk), ["hel", "l", "o\n"]);
  assert.equal(items().filter((item) => item.id === "opencode:tool:call" && item.status === "completed").length, 1);
  assert.equal(latest("opencode:tool:edit")?.diff, "-a\n+b");
  assert.equal(latest("opencode:tool:edit")?.newText, "b");
  assert.equal(latest("opencode:tool:task")?.childSessionId, "child");
  assert.equal(latest("opencode:part:child-part")?.parentItemId, "opencode:tool:task");
  assert.equal(latest("opencode:todo:root")?.steps?.[0]?.status, "running");
});

test("OpenCode v2 maps real SSE lifecycle, cumulative text and shell output once", () => {
  const { output, events, latest, items } = collect();
  const send = (type: string, data: Record<string, unknown>, id?: string) => output.update("v2", { type, data, ...(id ? { id } : {}) });
  send("session.text.started", { sessionID: "root", assistantMessageID: "msg", ordinal: 0 });
  send("session.text.delta", { sessionID: "root", assistantMessageID: "msg", ordinal: 0, delta: "Hi" }, "delta-1");
  send("session.text.delta", { sessionID: "root", assistantMessageID: "msg", ordinal: 0, delta: "Hi" }, "delta-1");
  send("session.text.ended", { sessionID: "root", assistantMessageID: "msg", ordinal: 0, text: "Hi there" });
  send("session.reasoning.delta", { sessionID: "root", assistantMessageID: "msg", ordinal: 0, delta: "think" });
  send("session.tool.input.started", { id: "call", name: "shell", sessionID: "root" });
  send("session.tool.input.delta", { id: "call", delta: '{"command":' });
  send("session.tool.input.ended", { id: "call", text: '{"command":"echo ok"}' });
  send("session.tool.called", { id: "call", input: { command: "echo ok" } });
  send("shell.created", { info: { id: "sh", metadata: { sessionID: "root" } } });
  send("shell.output", { id: "sh", chunk: "o" });
  send("shell.output", { id: "unrelated", chunk: "secret" });
  send("session.tool.progress", { id: "call", metadata: { shellID: "sh" } });
  const runningCount = items().filter((item) => item.id === "opencode:tool:call").length;
  assert.equal(latest("opencode:tool:call")?.output, undefined);
  send("shell.output", { id: "sh", chunk: "k\n" });
  assert.equal(items().filter((item) => item.id === "opencode:tool:call").length, runningCount);
  send("shell.exited", { id: "sh", exit: 0 });
  send("session.tool.success", { id: "call", content: [{ type: "text", text: "ok\n" }], metadata: { exit: 0, truncated: false } });
  send("session.tool.success", { id: "call", content: [{ type: "text", text: "ok\n" }], metadata: { exit: 0, truncated: false } });
  output.finish();
  assert.equal(latest("opencode:msg:text:0")?.text, "Hi there");
  assert.equal(latest("opencode:msg:reasoning:0")?.status, "completed");
  assert.deepEqual(events.filter((event) => event.type === "command.output").map((event) => event.type === "command.output" && event.chunk), ["o", "k\n"]);
  assert.equal(latest("opencode:tool:call")?.output, "ok\n");
  assert.equal(latest("opencode:tool:call")?.exitCode, 0);
  assert.equal(items().filter((item) => item.id === "opencode:tool:call" && item.status === "completed").length, 1);
});

test("OpenCode v2 projects files, search, plans, child tools and failures", () => {
  const { output, latest } = collect();
  const send = (type: string, data: Record<string, unknown>) => output.update("v2", { type, data });
  const call = (id: string, name: string, input: object) => {
    send("session.tool.input.started", { id, name, sessionID: "root" });
    send("session.tool.called", { id, input, sessionID: "root" });
  };
  call("file", "write", { path: "a.txt", content: "after" });
  send("session.tool.success", { id: "file", content: [{ type: "text", text: "written" }], metadata: { diff: "+after" } });
  call("search", "glob", { path: "src", pattern: "*.ts" });
  send("session.tool.success", { id: "search", content: [{ type: "text", text: "src/a.ts" }] });
  call("plan", "todowrite", { todos: [{ content: "first", status: "completed" }] });
  call("agent", "subagent", { prompt: "find it" });
  send("session.tool.progress", { id: "agent", metadata: { sessionID: "child" } });
  send("session.text.delta", { sessionID: "child", assistantMessageID: "child-msg", ordinal: 0, delta: "found" });
  send("session.tool.failed", { id: "agent", error: { type: "aborted", message: "interrupted" } });
  assert.equal(latest("opencode:tool:file")?.fileName, "a.txt");
  assert.equal(latest("opencode:tool:file")?.newText, "after");
  assert.equal(latest("opencode:tool:file")?.diff, "+after");
  assert.equal(latest("opencode:tool:search")?.results?.[0]?.text, "src/a.ts");
  assert.equal(latest("opencode:tool:plan")?.steps?.[0]?.status, "completed");
  assert.equal(latest("opencode:child-msg:text:0")?.parentItemId, "opencode:tool:agent");
  assert.equal(latest("opencode:tool:agent")?.status, "interrupted");
  assert.equal(latest("opencode:tool:agent")?.childSessionId, "child");
});
